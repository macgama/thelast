-- ---------- Spectateurs ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users on delete cascade,
  pseudo text not null default 'Spectateur' check (char_length(pseudo) between 2 and 24),
  lang text not null default 'fr' check (lang in ('fr', 'en')),
  role text not null default 'viewer' check (role in ('viewer', 'admin')),
  plan text not null default 'sub' check (plan in ('sub', 'free')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
$$;

create or replace function public.is_sub() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and plan = 'sub')
$$;

-- À l'inscription : on crée le profil. Le tout premier compte devient administrateur.
create or replace function public.on_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare p text := left(trim(coalesce(new.raw_user_meta_data->>'pseudo', '')), 24);
begin
  if char_length(p) < 2 then p := 'Spectateur ' || floor(random() * 9000 + 1000)::int; end if;
  insert into public.profiles (id, pseudo, lang, role)
  values (new.id, p, case when new.raw_user_meta_data->>'lang' = 'en' then 'en' else 'fr' end,
          case when exists (select 1 from public.profiles where role = 'admin') then 'viewer' else 'admin' end)
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.on_new_user();

drop policy if exists "profil : soi-même ou admin" on public.profiles;
create policy "profil : soi-même ou admin" on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists "profil : modifier le sien" on public.profiles;
create policy "profil : modifier le sien" on public.profiles for update using (id = auth.uid()) with check (id = auth.uid());
revoke update on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (pseudo, lang) on public.profiles to authenticated;

-- ---------- Saisons ----------
create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  name text not null default 'Saison 1',
  show text not null default 'survivor',
  seed int not null default floor(random() * 999999 + 1)::int,
  start_at timestamptz not null,
  status text not null default 'draft' check (status in ('draft', 'scheduled', 'live', 'done')),
  -- réglages du moteur (heures du vote, nombre de candidats, courbe d'élimination…)
  config jsonb not null default '{}',
  -- écrit par le moteur au lancement : casting (sans les secrets), île, catastrophes
  public jsonb,
  winner text,
  -- dernier passage du moteur : heure, jusqu'où c'est publié, textes écrits par l'IA, erreurs
  engine jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.seasons enable row level security;
drop policy if exists "saisons : visibles une fois programmées" on public.seasons;
create policy "saisons : visibles une fois programmées" on public.seasons for select using (status <> 'draft' or public.is_admin());
drop policy if exists "saisons : admin" on public.seasons;
create policy "saisons : admin" on public.seasons for all using (public.is_admin()) with check (public.is_admin());
grant select on public.seasons to anon, authenticated;
grant insert, update, delete on public.seasons to authenticated;

-- Ce que le moteur garde pour lui (pool figé, textes IA en cours) : invisible pour tout le monde sauf le moteur.
create table if not exists public.season_private (
  season_id bigint primary key references public.seasons on delete cascade,
  pool jsonb, catalog jsonb, looks jsonb, ai jsonb,
  updated_at timestamptz not null default now()
);
alter table public.season_private enable row level security;

-- ---------- Ce qui est diffusé, heure par heure ----------
-- kind : tick (une heure sur l'île, abonnés), conf (confessionnal, abonnés), daily (Quotidienne, tout le monde),
--        threat (les menacés du soir), secret (secret révélé), end (vainqueur)
create table if not exists public.reveals (
  season_id bigint not null references public.seasons on delete cascade,
  kind text not null,
  key text not null,
  reveal_at timestamptz not null,
  payload jsonb not null,
  hash text,
  updated_at timestamptz not null default now(),
  primary key (season_id, kind, key)
);
create index if not exists reveals_time on public.reveals (season_id, reveal_at);
alter table public.reveals enable row level security;
drop policy if exists "diffusion : à l'heure prévue" on public.reveals;
create policy "diffusion : à l'heure prévue" on public.reveals for select
  using (reveal_at <= now() and (kind not in ('tick', 'conf') or public.is_sub()));
grant select on public.reveals to anon, authenticated;

-- ---------- Heures de la saison ----------
-- Le jour 1 commence à 8h (start_at). Heure t de la simulation = minuit du jour 1 + t heures.
create or replace function public.season_base(s public.seasons) returns timestamptz
language sql immutable as $$ select s.start_at - interval '8 hours' $$;

create or replace function public.season_hour(s public.seasons, t int) returns timestamptz
language sql immutable as $$ select s.start_at - interval '8 hours' + t * interval '1 hour' $$;

create or replace function public.cfg_int(s public.seasons, k text, d int) returns int
language sql immutable as $$ select coalesce((s.config->>k)::int, d) $$;

-- ---------- Vote du soir : 1 vote gratuit par jour, même poids pour tous ----------
create table if not exists public.votes (
  season_id bigint not null references public.seasons on delete cascade,
  day int not null,
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  character_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (season_id, day, user_id)
);
alter table public.votes enable row level security;
drop policy if exists "votes : les siens" on public.votes;
create policy "votes : les siens" on public.votes for select using (user_id = auth.uid());
grant select on public.votes to authenticated;

-- Voter (ou changer d'avis) pendant que le vote est ouvert. Le jour est calculé ici, pas par le navigateur.
create or replace function public.cast_vote(p_season bigint, p_character text) returns json
language plpgsql security definer set search_path = public as $$
declare s public.seasons; d int; opens timestamptz; closes timestamptz;
begin
  if auth.uid() is null then raise exception 'login_required'; end if;
  select * into s from public.seasons where id = p_season and status in ('scheduled', 'live');
  if not found then raise exception 'no_season'; end if;
  d := floor(extract(epoch from now() - public.season_base(s)) / 86400)::int + 1;
  opens := public.season_hour(s, (d - 1) * 24 + public.cfg_int(s, 'voteOpenHour', 16));
  closes := public.season_hour(s, (d - 1) * 24 + public.cfg_int(s, 'voteHour', 19));
  if d < 1 or d >= public.cfg_int(s, 'days', 7) or now() < opens or now() >= closes then raise exception 'vote_closed'; end if;
  if not exists (select 1 from public.reveals r where r.season_id = p_season and r.kind = 'threat' and r.key = d::text
                 and r.reveal_at <= now() and r.payload->'ids' ? p_character) then
    raise exception 'not_threatened';
  end if;
  insert into public.votes (season_id, day, user_id, character_id) values (p_season, d, auth.uid(), p_character)
  on conflict (season_id, day, user_id) do update set character_id = excluded.character_id, updated_at = now();
  return json_build_object('day', d, 'character', p_character, 'closes', closes);
end $$;
grant execute on function public.cast_vote(bigint, text) to authenticated;

-- Résultats : seulement pour les votes clos. Pendant le vote, seulement le nombre de votants.
create or replace function public.vote_results(p_season bigint) returns table (day int, character_id text, votes bigint)
language sql stable security definer set search_path = public as $$
  select v.day, v.character_id, count(*) from public.votes v join public.seasons s on s.id = v.season_id
  where v.season_id = p_season and now() >= public.season_hour(s, (v.day - 1) * 24 + public.cfg_int(s, 'voteHour', 19))
  group by v.day, v.character_id
$$;
grant execute on function public.vote_results(bigint) to anon, authenticated;

create or replace function public.vote_count(p_season bigint, p_day int) returns bigint
language sql stable security definer set search_path = public as $$
  select count(*) from public.votes where season_id = p_season and day = p_day
$$;
grant execute on function public.vote_count(bigint, int) to anon, authenticated;

-- ---------- Colis : 1 par spectateur et par jour, gratuit ----------
-- Un colis envoyé avant midi arrive à midi le jour même ; après midi, le lendemain.
create table if not exists public.gifts (
  season_id bigint not null references public.seasons on delete cascade,
  gift_day int not null,
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  character_id text not null,
  item text not null check (item in ('flask', 'rations', 'medkit')),
  created_at timestamptz not null default now(),
  primary key (season_id, gift_day, user_id)
);
alter table public.gifts enable row level security;
drop policy if exists "colis : les siens" on public.gifts;
create policy "colis : les siens" on public.gifts for select using (user_id = auth.uid());
grant select on public.gifts to authenticated;

create or replace function public.send_gift(p_season bigint, p_character text, p_item text) returns json
language plpgsql security definer set search_path = public as $$
declare s public.seasons; d int; noon timestamptz; snap jsonb;
begin
  if auth.uid() is null then raise exception 'login_required'; end if;
  select * into s from public.seasons where id = p_season and status in ('scheduled', 'live');
  if not found then raise exception 'no_season'; end if;
  d := floor(extract(epoch from now() - public.season_base(s)) / 86400)::int + 1;
  noon := public.season_hour(s, (d - 1) * 24 + 12);
  if now() >= noon then d := d + 1; end if;
  if d < 1 or d > public.cfg_int(s, 'days', 7) then raise exception 'gift_closed'; end if;
  select r.payload->'s' into snap from public.reveals r
    where r.season_id = p_season and r.kind = 'tick' and r.reveal_at <= now() order by r.reveal_at desc limit 1;
  if snap is not null and not snap ? p_character then raise exception 'not_in_game'; end if;
  insert into public.gifts (season_id, gift_day, user_id, character_id, item) values (p_season, d, auth.uid(), p_character, p_item);
  return json_build_object('day', d, 'arrives', public.season_hour(s, (d - 1) * 24 + 12));
exception when unique_violation then raise exception 'gift_used';
end $$;
grant execute on function public.send_gift(bigint, text, text) to authenticated;

-- ---------- Back-office : personnages, catastrophes, réglages ----------
create table if not exists public.characters (
  id text primary key,
  data jsonb not null,
  look jsonb,
  photo text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
create table if not exists public.catastrophes (
  id text primary key,
  kind text not null default 'individual' check (kind in ('individual', 'island')),
  data jsonb not null,
  active boolean not null default true,
  sort int not null default 0,
  updated_at timestamptz not null default now()
);
create table if not exists public.settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);
do $$ declare t text; begin
  foreach t in array array['characters', 'catastrophes', 'settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "admin" on public.%I', t);
    execute format('create policy "admin" on public.%I for all using (public.is_admin()) with check (public.is_admin())', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- Liste des spectateurs pour le back-office (avec leur e-mail, visible des seuls admins)
create or replace function public.admin_users() returns table (id uuid, email text, pseudo text, role text, plan text, created_at timestamptz, votes bigint)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'admin_only'; end if;
  return query select p.id, u.email::text, p.pseudo, p.role, p.plan, p.created_at,
    (select count(*) from public.votes v where v.user_id = p.id)
  from public.profiles p join auth.users u on u.id = p.id order by p.created_at;
end $$;
grant execute on function public.admin_users() to authenticated;

create or replace function public.admin_set_profile(p_user uuid, p_role text, p_plan text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'admin_only'; end if;
  if p_user = auth.uid() and p_role <> 'admin' then raise exception 'keep_one_admin'; end if;
  update public.profiles set role = p_role, plan = p_plan where id = p_user;
end $$;
grant execute on function public.admin_set_profile(uuid, text, text) to authenticated;

-- Recommencer une saison de zéro (efface la diffusion, les votes et les colis de cette saison)
create or replace function public.admin_reset_season(p_season bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'admin_only'; end if;
  delete from public.reveals where season_id = p_season;
  delete from public.votes where season_id = p_season;
  delete from public.gifts where season_id = p_season;
  delete from public.season_private where season_id = p_season;
  update public.seasons set public = null, winner = null, engine = null,
    status = case when status = 'draft' then 'draft' else 'scheduled' end, updated_at = now() where id = p_season;
end $$;
grant execute on function public.admin_reset_season(bigint) to authenticated;

-- Statistiques de la saison pour le back-office
create or replace function public.admin_stats(p_season bigint) returns json
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'admin_only'; end if;
  return json_build_object(
    'viewers', (select count(*) from public.profiles),
    'votes', (select coalesce(json_agg(x order by x.day), '[]') from (select day, count(*) n from public.votes where season_id = p_season group by day) x),
    'gifts', (select count(*) from public.gifts where season_id = p_season),
    'published', (select count(*) from public.reveals where season_id = p_season and kind = 'tick'),
    'shown', (select count(*) from public.reveals where season_id = p_season and kind = 'tick' and reveal_at <= now()));
end $$;
grant execute on function public.admin_stats(bigint) to authenticated;

